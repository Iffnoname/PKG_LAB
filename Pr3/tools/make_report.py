def TABLE(caption, header, rows, widths=None):
    tab_n[0] += 1
    c = doc.add_paragraph()
    c.paragraph_format.first_line_indent = Cm(0)
    c.paragraph_format.keep_with_next = True
    c.add_run(f"Таблица {tab_n[0]}. {caption}").font.size = Pt(12)
    t = doc.add_table(rows=1 + len(rows), cols=len(header))
    t.style = "Table Grid"
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    for i, row in enumerate([header] + rows):
        for j, v in enumerate(row):
            cell = t.cell(i, j)
            cell.text = ""
            p = cell.paragraphs[0]
            p.paragraph_format.first_line_indent = Cm(0)
            p.paragraph_format.line_spacing = 1.0
            p.alignment = WD_ALIGN_PARAGRAPH.CENTER if j > 0 or i == 0 else WD_ALIGN_PARAGRAPH.LEFT
            r = p.add_run(str(v))
            r.font.size = Pt(11)
            r.bold = i == 0
            if widths:
                cell.width = Cm(widths[j])
    doc.add_paragraph().paragraph_format.line_spacing = 0.8
    return tab_n[0]


